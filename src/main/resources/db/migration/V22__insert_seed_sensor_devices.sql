-- 불일치 시 에러가 아니라 조용히 NULL 이 들어가 실패를 놓친다.
-- 센서-공간 배치는 공간 명칭 확정 후 UPDATE 로 처리한다.
--
-- expected_interval_seconds 는 관측 중앙값이 아니라 그 값이 수렴하는 공칭 주기를 쓴다.
-- (121.8 -> 120, 599.9 -> 600). 관측값의 소수점 편차는 장비 드리프트다.

