-- 임계치 룰이 device_eui 를 FK 로 참조하므로 룰 등록 전에 장비 목록이 존재해야 한다.
--
-- 아래 값은 MQTT 실측 관측 결과다. device_eui 는 관측 표에서 생략된 공통 접두사
