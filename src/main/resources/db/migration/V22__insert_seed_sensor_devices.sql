-- 무응답 장비(126d152590 / 128c067999)는 의도적으로 제외했다.
-- 유입이 0건이라 모델·주기를 관측으로 확정할 수 없어, 추측값을 정본에 넣는 대신
-- 응답이 확인된 시점에 별도 마이그레이션으로 추가한다.

-- 시드가 실제로 적재됐는지 배포 시점에 확인한다.
DO $$
DECLARE
    seeded INTEGER;
BEGIN
    SELECT count(*) INTO seeded
    FROM learning_service.sensor_devices
    WHERE device_eui LIKE '24e124%';

    IF seeded < 8 THEN
        RAISE EXCEPTION '센서 시드 적재 실패: 기대 8건, 실제 %건', seeded;
    END IF;
END
$$;
